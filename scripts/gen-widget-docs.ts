/**
 * Generates docs/widget-customization.md from the widget config descriptor.
 *
 * The descriptor is the single source of truth; this keeps the public
 * reference from drifting away from it. `--check` fails instead of writing,
 * which is what CI runs.
 *
 * Usage: pnpm docs:widget [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import {
  DEFAULTS,
  PARTS,
  SLOTS,
  TOKENS,
  WIDGET_OPTIONS,
} from "../packages/shared/src/widget-config";
import {
  type OptionGroup,
  TOKEN_HELP,
  WIDGET_OPTION_META,
} from "../packages/shared/src/widget-config-meta";

const OUT = new URL("../docs/widget-customization.md", import.meta.url).pathname;

const GROUPS: OptionGroup[] = ["Identity", "Theme", "Launcher", "Behaviour", "Content"];

function typeOf(key: string): string {
  const option = WIDGET_OPTIONS.find((o) => o.key === key);
  if (!option) return "";
  if (option.kind === "enum") return option.values?.map((v) => `\`${v}\``).join(" \\| ") ?? "";
  if (option.kind === "stringList") return `list, max ${option.max}`;
  if (option.kind === "theme") return "object";
  if (option.kind === "copy") return "object";
  if (option.kind === "promptGroups" || option.kind === "reasons") return "JSON array";
  if (option.kind === "int") return "number";
  if (option.kind === "css") return "CSS value";
  return option.kind;
}

function defaultOf(key: string): string {
  const value = DEFAULTS[key as keyof typeof DEFAULTS];
  if (value === "") return "—";
  if (Array.isArray(value)) return value.length ? `\`${value.join("|")}\`` : "—";
  if (typeof value === "object") return "—";
  return `\`${String(value)}\``;
}

const lines: string[] = [];
const w = (s = "") => lines.push(s);

w("<!-- Generated by scripts/gen-widget-docs.ts — run `pnpm docs:widget`. Do not edit. -->");
w();
w("# Customizing the Deskbell widget");
w();
w("Four layers, each an escape hatch for the one below. Most deployments stop at the first.");
w();
w("1. **Dashboard** — set appearance on the Appearance page; no code, no redeploy.");
w("2. **Attributes** — override anything per page from the embed code.");
w("3. **CSS** — `--deskbell-*` custom properties for colour, and `::part()` for shape.");
w("4. **Slots** — replace the launcher, header, empty state or footer with your own markup.");
w();
w("Precedence, lowest to highest:");
w();
w("```");
w("defaults  <  dashboard config  <  attributes / JS config  <  host-page CSS");
w("```");
w();
w("Host-page CSS wins last on purpose. `deskbell-widget { --deskbell-accent: red }` is the");
w("most explicit statement of intent on the page, so nothing resolved at runtime beats it.");
w();
w("## Quick start");
w();
w("One tag. There is no `api-url` to configure: `deskbell.js` is served by your own");
w("Deskbell deployment, so the script's origin is the API origin.");
w();
w("```html");
w("<script");
w("  async");
w('  src="https://your-deskbell/deskbell.js"');
w('  data-project-key="pk_live_..."');
w('  data-accent="#2b6b4f"');
w('  data-color-scheme="auto"');
w('  data-launcher-label="Ask AI"');
w('  data-suggested-questions="How do I install?|What does it cost?"');
w("></script>");
w("```");
w();
w("Every option below works as `data-<attribute>` on that tag.");
w();
w("List options (`suggested-questions`) are separated by `|`, because questions contain");
w("commas. Object options (`theme`, `copy`, `prompt-groups`, `feedback-reasons`) take JSON.");
w();
w("### Placing the element yourself");
w();
w("Drop `data-project-key` and write the element instead when you need to control where");
w("it sits in the DOM. Auto-mount stands down whenever a `<deskbell-widget>` already");
w("exists, so the two never collide.");
w();
w("```html");
w('<script async src="https://your-deskbell/deskbell.js"></script>');
w("<deskbell-widget");
w('  project-key="pk_live_..."');
w('  api-url="https://your-deskbell"');
w('  color-scheme="auto"');
w("></deskbell-widget>");
w("```");
w();
w("The two forms use the same names — the script tag prefixes them with `data-`.");
w("The table below gives the element form.");
w();
w("## Options");
w();
for (const group of GROUPS) {
  const rows = WIDGET_OPTIONS.filter((o) => WIDGET_OPTION_META[o.key].group === group);
  if (rows.length === 0) continue;
  w(`### ${group}`);
  w();
  w("| Attribute | Type | Default | Description |");
  w("| --- | --- | --- | --- |");
  for (const option of rows) {
    const meta = WIDGET_OPTION_META[option.key];
    w(`| \`${option.attr}\` | ${typeOf(option.key)} | ${defaultOf(option.key)} | ${meta.help} |`);
  }
  w();
}
w("## Theme tokens");
w();
w("Set these anywhere in your CSS — they pierce the shadow boundary. Colour tokens have");
w("light and dark values built in; `color-scheme` picks between them.");
w();
w("```css");
w("deskbell-widget {");
w("  --deskbell-accent: #2b6b4f;");
w("  --deskbell-surface: #ffffff;");
w("  --deskbell-radius: 16px;");
w("}");
w("```");
w();
w("| Token | Purpose |");
w("| --- | --- |");
for (const token of TOKENS) {
  w(`| \`--deskbell-${token}\` | ${TOKEN_HELP[token]} |`);
}
w();
w("## Parts");
w();
w("For anything a token cannot express — spacing, borders, layout — style the element");
w("directly with `::part()`.");
w();
w("```css");
w("deskbell-widget::part(launcher) { border-radius: 8px; }");
w("deskbell-widget::part(panel) { width: 520px; }");
w("```");
w();
w(PARTS.map((p) => `\`${p}\``).join(" · "));
w();
w("A citation pill also carries `citation-kind-<type>` for its source's connector type,");
w("e.g. `::part(citation-kind-docs-crawler)`.");
w();
w("## Slots");
w();
w("Put your own markup in a slot and it replaces the default entirely — no JS, and the");
w("launcher stays wired: clicking your button opens the widget.");
w();
w("```html");
w('<deskbell-widget project-key="pk_live_...">');
w('  <button slot="launcher" class="my-button">Need help?</button>');
w("</deskbell-widget>");
w("```");
w();
w(SLOTS.map((s) => `\`${s}\``).join(" · "));
w();
w("## Recipes");
w();
w("Layouts the options do not cover but CSS does. Rules the host page writes against");
w("`::part()` beat the widget's own \u2014 normal declarations from the outer page win over");
w("shadow-tree rules \u2014 so none of this needs `!important`.");
w();
w("### A full-height side panel");
w();
w("```html");
w("<script");
w("  async");
w('  src="https://your-deskbell/deskbell.js"');
w('  data-project-key="pk_live_..."');
w('  data-position="bottom-left"');
w('  data-launcher="none"');
w('  data-open-on-load="true"');
w("></script>");
w("```");
w();
w("```css");
w("deskbell-widget::part(panel) {");
w("  top: 0;");
w("  bottom: 0;");
w("  left: 0;");
w("  height: auto;");
w("  width: min(420px, 100vw);");
w("  border-radius: 0;");
w("}");
w();
w("/* The widget is position: fixed and overlays the page \u2014 make room for it. */");
w("body {");
w("  padding-left: min(420px, 100vw);");
w("}");
w("```");
w();
w("Pinning `top` and `bottom` is enough: leave `height: auto` and the panel fills the gap.");
w("Avoid `height: 100vh`, which is wrong on mobile where browser chrome overlaps the");
w("viewport, and there is no `max-height` to clear.");
w();
w('Set `position="bottom-left"` even though the `::part()` rule already sets `left`. It');
w("clears the default `right` offset, which an RTL page would otherwise honour \u2014 snapping");
w("the rail back to the opposite edge.");
w();
w('`launcher="none"` drops the bubble and `open-on-load` keeps the rail up; omit both to');
w("open it from your own control instead. The close button still renders \u2014 hide it with");
w("`deskbell-widget::part(close-button) { display: none }` if the rail should never close.");
w();
w("### What CSS cannot do");
w();
w("Recent conversations and the open thread are one view, not two panes: the widget shows");
w("one or the other, never both. A layout with the conversation list permanently beside the");
w("thread is out of reach from CSS, because the markup for both never exists at once.");
w();
w("## JavaScript API");
w();
w("```js");
w('deskbell("open");');
w('deskbell("close");');
w('deskbell("toggle");');
w('deskbell("open", { query: "How do I install?", submit: true });');
w('deskbell("ask", "How do I install?");');
w('deskbell("config", { accent: "#7c3aed", colorScheme: "dark" });');
w('deskbell("on", "answer", (e) => analytics.track("Docs answered", e.detail));');
w('deskbell("auth", () => session.accessToken); // signed-in visitors, see docs/widget/identity');
w('deskbell("mount"); // with data-render-on-load="false" on the script tag');
w('deskbell("unmount");');
w("```");
w();
w("To call it before `deskbell.js` has loaded, install the queueing stub first — calls");
w("are replayed in order once the bundle takes over:");
w();
w("```html");
w("<script>");
w("  window.deskbell = function () {");
w("    (window.deskbell.q ??= []).push(arguments);");
w("  };");
w("</script>");
w("```");
w();
w("`config` cannot override anything the host page set in CSS — see the precedence above.");
w();
w("## Events");
w();
w("The widget dispatches `CustomEvent`s on `window`, so a tag manager can read them with");
w("no SDK.");
w();
w("```js");
w('window.addEventListener("deskbell:answer", (e) => {');
w('  analytics.track("Docs answered", e.detail);');
w("});");
w("```");
w();
w("| Event | `detail` |");
w("| --- | --- |");
w("| `deskbell:ready` | — (once per element, after the first paint) |");
w("| `deskbell:opened` | — |");
w("| `deskbell:closed` | — |");
w("| `deskbell:question` | `question`, `conversationId` |");
w(
  "| `deskbell:answer` | `question`, `conversationId`, `messageId`, `answer`, `citations`, `unsupportedTerms` (only when the answer named things the documentation does not contain) |",
);
w("| `deskbell:refusal` | `question`, `reason` |");
w("| `deskbell:feedback` | `messageId`, `feedback` |");
w("| `deskbell:limited` | `question`, `retryAfter` |");
w("| `deskbell:link` | `href` |");
w("| `deskbell:citation` | `href`, `documentId`, `title` |");
w("| `deskbell:conversation` | `id`, `action` (`created`, `opened`, `reset`, `deleted`) |");
w("| `deskbell:unauthorized` | `question` |");
w("| `deskbell:preview` | `conversationId`, `title`, `owner`, `context` |");
w("| `deskbell:error` | `question`, `status` |");
w();
w("A refusal is a docs gap, not a failure — it is the most valuable event here.");
w();

const output = `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== output) {
    console.error("docs/widget-customization.md is stale — run `pnpm docs:widget`.");
    process.exit(1);
  }
  console.log("docs/widget-customization.md is current.");
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT}`);
}
